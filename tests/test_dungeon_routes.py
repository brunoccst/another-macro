"""The Another Dungeons' fixed walking routes (dungeon_routes.py, the dungeon macros' `path:`)."""
import re

import pytest

from another_macro import dungeon_routes as dr


@pytest.fixture(scope="module")
def table():
    return dr.WalkTable.load()


def mapped():
    return [(did, idx, m, raw) for did, idx, m, raw in dr.load_maps() if m is not None]


def dogma_map_1():
    """Dogma Tower's first map (measured on the phone)."""
    return next(m for did, idx, m, _ in dr.load_maps(dr.MACROS / "dogma-tower.yaml") if idx == 0)


def test_walk_table_round_trips(table):
    for ms in (100, 250, 600, 1000, 2200, 4000, 6500):
        assert table.hold_ms(table.distance(ms)) == pytest.approx(ms, abs=1e-6)
    # measured points
    assert table.distance(1000) == pytest.approx(0.0244)
    assert table.distance(5000) == pytest.approx(0.0970 + 0.026)


@pytest.mark.parametrize("did,idx,m,raw", mapped(), ids=lambda v: str(v) if isinstance(v, (str, int)) else "")
def test_path_takes_every_chest_then_the_exit(did, idx, m, raw, table):
    legs = raw["path"]
    targets = [leg[0] for leg in legs]
    want = [f"chest {i + 1}" for i in range(len(m.chests))] + [f"sparkle {i + 1}" for i in range(len(m.sparkles))]
    want += [f"fish {i + 1}" for i in range(len(m.fish))] + [f"jar {i + 1}" for i in range(len(m.jars))]
    assert sorted(targets[:-1]) == sorted(want)
    assert targets[-1] == "exit"
    pos = m.arrival
    for leg in legs:
        pos = dr.run_steps(m, table, pos, leg[1:])  # raises if a flick isn't at stairs
        kind, _, n = leg[0].partition(" ")
        stops = {"chest": m.chests, "sparkle": m.sparkles, "fish": m.fish, "jar": m.jars}
        goal = m.exit if kind == "exit" else stops[kind][int(n) - 1]
        assert dr.seg_of(m, pos) == dr.seg_of(m, goal), f"{leg[0]}: ended on the wrong street at {pos}"
        assert abs(pos[0] - goal[0]) <= table.wall_snap, f"{leg[0]}: ended at x={pos[0]:.3f}, goal {goal[0]:.3f}"


@pytest.mark.parametrize("f", dr.dungeon_files(), ids=lambda f: f.stem)
def test_paths_in_the_macro_files_are_up_to_date(f, table):
    assert dr.render(f, table) == f.read_text(encoding="utf-8"), "run `another-macro dungeon-routes --write`"


@pytest.mark.parametrize("f", dr.dungeon_files(), ids=lambda f: f.stem)
def test_render_writes_missing_paths_back(f, tmp_path, table):
    """A file whose paths were taken out gets the same ones back, at any indent (an area's maps sit deeper)."""
    text = f.read_text(encoding="utf-8")
    p = tmp_path / f.name
    p.write_text(re.sub(r"(?m)^( *)# generated by .*\n\1path:\n(\1  - .*\n)+", "", text), encoding="utf-8")
    assert p.read_text(encoding="utf-8") != text or "path:" not in text
    once = dr.render(p, table)
    assert once == text
    p.write_text(once, encoding="utf-8")
    assert dr.render(p, table) == once


def test_stairs_need_the_party_on_them(table):
    m = dogma_map_1()
    with pytest.raises(ValueError):
        dr.flick(m, m.arrival, up=True)  # map 1's arrival isn't at stairs


def test_a_walk_stops_at_the_wall(table):
    m = dogma_map_1()
    end = dr.walk(m, table, m.arrival, right=False, ms=20000)
    assert end[0] == pytest.approx(0.374)  # map 1's bottom street starts at x 0.374 (measured on the phone)
