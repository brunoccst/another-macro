"""Deterministic routes to the Cat Scratchbook cats (`another-macro cat-routes`).

Like the Another Dungeon paths (dungeon_routes.py), the whole trip to a cat is a fixed list of
actions (how the cats move: docs/knowledge-base/learned/cat-scratchbook.md):

1. **Point zero**: the World Map on the Present era with Baruoki's label on screen.
2. **World map**: the era tab (if not Present) and Expand -> continent (only when set), then the
place's label by OCR (a label has no fixed screen spot; the search starts from the view the
era tab opens). Then the sub-location's panel entry (`sub`) and Yes.
3. **Area map**: the party arrives at a fixed spot (`area.arrival`); the fixed moves (`path`,
   generated here from the street layout, the walk table and the map's `walk_scale`) take it to
   the cat's start (`area.cat`).
4. **Drift**: the cat wanders along its street up to `area.drift` = [left, right] from its start;
   the app looks for the feather bubble at the start, then at each end of that range.

The data is `scenarios/cat_scratchbook/templates/cat_spots.yaml`, keyed by the clue's
`location` in riddles.yaml. Positions are measured on the phone (the `map-dungeon` way: the
opened area map, fractions of a 2400x1080 screen). A spot whose measurements are missing has no
`path` and the app finds the cat the old way (searching the world map by OCR, steering by the
area map's feather icon).
"""
from __future__ import annotations

import json
import re
from pathlib import Path

import yaml

from . import dungeon_routes as dr

SPOTS = Path(__file__).resolve().parent / "scenarios" / "cat_scratchbook" / "templates" / "cat_spots.yaml"
RIDDLES = Path(__file__).resolve().parent / "scenarios" / "cat_scratchbook" / "riddles.yaml"

AREA_KEYS = ("segs", "arrival", "cat")


def load_spots(path: Path = SPOTS) -> dict[str, dict]:
    return yaml.safe_load(path.read_text(encoding="utf-8")) or {}


def scaled(t: dr.WalkTable, scale: float) -> dr.WalkTable:
    """The walk table for a map whose area map is drawn [scale] times as large as walk.yaml's.

    The same hold walks the same distance in the game, but each area map has its own zoom, so
    the distance in area-map units differs by map (measured once per map: hold R 3000 from rest
    and compare with walk.yaml's 0.0709).
    """
    if scale == 1.0:
        return t
    data = {
        "hold_ms": t.ms,
        "distance": [d * scale for d in t.dist],
        "beyond_per_s": t.beyond * scale,
        "flick_ms": t.flick_ms,
        "min_walk": t.min_walk,
        "wall_snap": t.wall_snap,
        "wall_margin": t.wall_margin,
    }
    return dr.WalkTable(data)


def area_map(name: str, spot: dict) -> dr.MapData | None:
    """The spot's map as a layout the dungeon planner understands, the cat as its only stop."""
    a = spot.get("area") or {}
    if any(a.get(k) is None for k in AREA_KEYS):
        return None  # unmeasured
    # a walk_to spot's area is the map walked into: its arrival is where walking across leaves the party
    return dr.MapData(
        name=name,
        segs=[dr.Seg(*s) for s in a["segs"]],
        links=[dr.Link(*ln) for ln in a.get("links") or []],
        chests=[],
        arrival=tuple(a["arrival"]),
        exit=tuple(a["cat"]),
    )


def drift_range(name: str, spot: dict) -> tuple[float, float]:
    """Where on its street the cat can be: (x from, x to), inside the street."""
    m = area_map(name, spot)
    assert m is not None
    left, right = (spot["area"].get("drift") or [0.0, 0.0])
    cat = m.exit
    s = dr.seg_of(m, cat)
    if s is None:
        raise ValueError(f"{name}: the cat {cat} is on no street")
    return max(s.x1, cat[0] - left), min(s.x2, cat[0] + right)


def plan(name: str, spot: dict, t: dr.WalkTable) -> list[str] | None:
    """The fixed moves from the arrival to the cat's start, or None while unmeasured."""
    m = area_map(name, spot)
    if m is None:
        return None
    tt = scaled(t, float(spot["area"].get("walk_scale") or 1.0))
    _, moves = dr._route(m, tt, m.arrival, m.exit)
    steps, _ = dr._leg_steps(m, tt, m.arrival, m.exit, moves)
    return steps


def follow(name: str, spot: dict, t: dr.WalkTable, steps: list[str]) -> tuple[float, float]:
    """Where the moves leave the party (the rules the app follows too)."""
    m = area_map(name, spot)
    assert m is not None
    return dr.run_steps(m, scaled(t, float(spot["area"].get("walk_scale") or 1.0)), m.arrival, steps)


def missing(spot: dict) -> list[str]:
    """What still has to be measured on the phone for a fully fixed trip."""
    a = spot.get("area") or {}
    out = [f"area.{k}" for k in AREA_KEYS if a.get(k) is None]
    if a.get("walk_scale") is None:
        out.append("area.walk_scale")
    if a.get("drift") is None:
        out.append("area.drift")
    return out


# --- writing the paths into cat_spots.yaml ---------------------------------------------
_TOP = re.compile(r"^[^\s#].*:\s*$")
_GEN = "  # generated by `another-macro cat-routes --write`"


def safe_plan(name: str, spot: dict, t: dr.WalkTable) -> list[str] | None:
    """[plan], or None (with a printed reason) when the measured layout doesn't connect."""
    try:
        return plan(name, spot, t)
    except ValueError as e:
        print(f"{name}: no route from the measured layout ({e}); fix its area by hand")
        return None


def render(path: Path = SPOTS, table: dr.WalkTable | None = None) -> str:
    """cat_spots.yaml with every measured spot's `path:` (re)generated; the rest kept as written."""
    t = table or dr.WalkTable.load()
    spots = load_spots(path)
    lines = path.read_text(encoding="utf-8").splitlines(keepends=True)
    starts = [i for i, ln in enumerate(lines) if _TOP.match(ln)]
    assert len(starts) == len(spots), "every spot must start with an unindented 'Name:' line"
    out = lines[: starts[0]] if starts else lines
    bounds = starts + [len(lines)]
    for k, name in enumerate(spots):
        block = lines[bounds[k] : bounds[k + 1]]
        end = len(block)
        while end > 1 and (not block[end - 1].startswith("  ") or block[end - 1].strip() == ""):
            end -= 1
        body = [ln for ln in block[:end] if not ln.startswith("  path:") and not ln.startswith(_GEN)]
        steps = safe_plan(name, spots[name], t)
        if steps is not None:
            body += [f"{_GEN}\n", f"  path: [{', '.join(steps)}]\n"]
        out += body + block[end:]
    return "".join(out)


# --- importing what the phone measured -----------------------------------------------------
# When a cat's spot has no fixed route, the app measures it before the hunt (CatSurvey.kt) and
# logs one "MEASURED cat spot: {json}" line (macro_status with find "MEASURED cat spot").
MEASURED = re.compile(r"MEASURED cat spot: (\{.*\})")


def parse_measured(text: str) -> dict[str, dict]:
    """The measured spots in a log, by location (a later line for the same spot wins)."""
    out: dict[str, dict] = {}
    for m in MEASURED.finditer(text):
        data = json.loads(m.group(1))
        out[data["location"]] = data
    return out


def _flow(v) -> str:
    return json.dumps(v, separators=(", ", ": "))


def bridge_icons(m: dict, max_gap: float = 0.1, reach: float = 0.05) -> list[str]:
    """Close the street gaps the party marker and the feather leave in the survey's street read.

    The icons are drawn on the street and aren't street-grey, so the read splits a street where
    they sit. Two pieces of one row either side of the icon become one street; a lone piece
    reaching toward it is stretched to it. Returns what was changed (for the notes).
    """
    segs = [list(s) for s in m.get("segs") or []]
    done = []
    for key in ("arrival", "cat"):
        p = m.get(key)
        if not p:
            continue
        x, y = p
        row = [s for s in segs if abs(s[0] - y) < 0.035]
        if any(s[1] - 0.004 <= x <= s[2] + 0.004 for s in row):
            continue
        left = max((s for s in row if s[2] < x), key=lambda s: s[2], default=None)
        right = min((s for s in row if s[1] > x), key=lambda s: s[1], default=None)
        if left and right and abs(left[0] - right[0]) < 0.01 and right[1] - left[2] <= max_gap:
            segs.remove(right)
            left[2] = right[2]
            done.append(f"{key}: joined the street at y {left[0]} across the icon ({left[1]}-{left[2]})")
        elif left and x - left[2] <= reach:
            left[2] = round(x + 0.01, 3)
            done.append(f"{key}: stretched the street at y {left[0]} to {left[2]}")
        elif right and right[1] - x <= reach:
            right[1] = round(x - 0.01, 3)
            done.append(f"{key}: stretched the street at y {right[0]} to {right[1]}")
    m["segs"] = segs
    return done


def area_block(m: dict) -> list[str]:
    """The `area:` lines of cat_spots.yaml for one measured spot."""
    lines = ["  area:\n"]
    where = f" (map '{m['map']}')" if m.get("map") else ""
    lines.append(f"    # measured by the app's survey {m.get('date', '')}{where}: check it, then test it live\n")
    for note in m.get("notes") or []:
        lines.append(f"    # survey note: {note}\n")
    if m.get("feather_reads"):
        lines.append(f"    # feather x reads: {_flow(m['feather_reads'])}\n")
    for key in ("segs", "links", "arrival", "cat", "drift", "walk_scale"):
        if m.get(key) is not None:
            lines.append(f"    {key}: {_flow(m[key])}\n")
    return lines


def import_measured(text: str, path: Path = SPOTS, force: bool = False) -> tuple[str, list[str], list[str]]:
    """cat_spots.yaml with the measured areas in (paths not regenerated): (text, imported, skipped).

    A spot that already has an area is kept unless [force] (hand measurements win).
    """
    measured = parse_measured(text)
    spots = load_spots(path)
    lines = path.read_text(encoding="utf-8").splitlines(keepends=True)
    starts = [i for i, ln in enumerate(lines) if _TOP.match(ln)]
    bounds = starts + [len(lines)]
    out = lines[: starts[0]] if starts else list(lines)
    imported, skipped = [], []
    for k, name in enumerate(spots):
        block = lines[bounds[k] : bounds[k + 1]]
        m = measured.get(name)
        if m is None:
            out += block
            continue
        if spots[name].get("area") and not force:
            skipped.append(f"{name} (already has an area; --force replaces it)")
            out += block
            continue
        bridged = bridge_icons(m)
        if bridged:
            m["notes"] = list(m.get("notes") or []) + [f"import: {b}" for b in bridged]
        i = next(j for j, ln in enumerate(block) if ln.startswith("  area:"))
        j = i + 1
        while j < len(block) and (block[j].startswith("    ") or block[j].strip() == ""):
            j += 1
        rest = [ln for ln in block[j:] if not ln.startswith("  path:") and not ln.startswith(_GEN)]
        out += block[:i] + area_block(m) + rest
        imported.append(name)
    skipped += [f"{n} (no such spot in cat_spots.yaml)" for n in measured if n not in spots]
    return "".join(out), imported, skipped


def skeleton(riddles: Path = RIDDLES, spots: Path = SPOTS) -> str:
    """Entries for riddles.yaml locations that cat_spots.yaml doesn't have yet (to append)."""
    have = load_spots(spots) if spots.is_file() else {}
    seen, out = set(), []
    for r in (yaml.safe_load(riddles.read_text(encoding="utf-8")) or {}).values():
        loc = r.get("location")
        if not loc or loc in have or loc in seen:
            continue
        seen.add(loc)
        place, sub = split_location(loc)
        via = re.search(r"\(Enter from ([^)]*)\)", loc)
        if via:  # the cat is on the map next to the travel point: travel there, walk across
            place, sub = via.group(1), None
        out.append(
            f"{_scalar(loc)}:\n"
            f"  era: {r.get('era') or 'null'}\n"
            f"  continent: null\n"
            f"  place: {_scalar(place)}\n"
            f"  sub: {_scalar(sub) if sub else 'null'}\n"
            + (f"  walk_to: {_scalar(split_location(loc)[0])}\n" if via else "")
            + "  area: null\n"
        )
    return "".join(out)


def _scalar(v: str) -> str:
    """v as a one-line YAML scalar (quoted when it needs to be)."""
    return yaml.safe_dump({"k": v}, allow_unicode=True, width=10_000).strip()[3:]


def split_location(loc: str) -> tuple[str, str | None]:
    """'Moonlight Forest (Forest Edge)' -> ('Moonlight Forest', 'Forest Edge'), the CatDaily rule."""
    m = re.match(r"^(.*?)\s*\(([^)]*)\)\s*$", loc)
    if m and not m.group(2).startswith("Enter from") and "quick destination" not in m.group(2):
        return m.group(1), m.group(2)
    if m:
        return m.group(1), None
    m = re.match(r"^(.*?)\s+[–-]\s+(.+)$", loc)
    if m:
        return m.group(1), m.group(2)
    return loc, None


def main(write: bool = False, check: bool = False, todo: bool = False, import_from: str | None = None, force: bool = False) -> int:
    t = dr.WalkTable.load()
    if import_from:
        log = Path(import_from).read_text(encoding="utf-8")
        text, imported, skipped = import_measured(log, SPOTS, force)
        for s in skipped:
            print(f"skipped {s}")
        if not imported:
            print("nothing imported (no new 'MEASURED cat spot:' lines)")
        else:
            SPOTS.write_text(text, encoding="utf-8")
            print(f"imported {', '.join(imported)}")
            write = True  # their paths
    spots = load_spots()
    ready = 0
    for name, spot in spots.items():
        steps = safe_plan(name, spot, t)
        if steps is not None:
            ready += 1
            lo, hi = drift_range(name, spot)
            print(f"{name} ({spot.get('era')}): {', '.join(steps) or '(arrives at the cat)'}; cat drifts x {lo:.3f}-{hi:.3f}")
        elif todo:
            print(f"{name} ({spot.get('era')}): to measure: {', '.join(missing(spot))}")
    print(f"{ready}/{len(spots)} spots have a fixed route")
    new = render(SPOTS, t)
    current = SPOTS.read_text(encoding="utf-8")
    if check and new != current:
        print("cat_spots.yaml paths are out of date: run `another-macro cat-routes --write`")
        return 1
    if write and new != current:
        SPOTS.write_text(new, encoding="utf-8")
        print(f"wrote {SPOTS}")
    return 0
